import type { ProbeResult } from '@tsinspect/core';
import { formatBytes, hex16 } from '@tsinspect/core';

export interface HtmlTableOptions {
  all?: boolean;
}

/** Standalone HTML table index used by `tsinspect tables --format html`. */
export function formatTableIndexHtml(
  result: ProbeResult,
  options: HtmlTableOptions = {},
): string {
  const all = options.all ?? false;
  const visible = all
    ? result.tables
    : result.tables.filter((table) => table.tableId !== 0xff);

  const rows = visible
    .map(
      (table) => `<tr>
        <td class="mono">${hex16(table.pid)}</td>
        <td>${escapeHtml(table.name)}</td>
        <td class="mono">${escapeHtml(table.tableIdHex)}</td>
        <td class="mono">${table.tableIdExtension !== undefined ? hex16(table.tableIdExtension) : '-'}</td>
        <td class="num">${table.version ?? '-'}</td>
        <td class="num">${
          table.sectionNumber !== undefined
            ? `${table.sectionNumber}/${table.lastSectionNumber ?? '-'}`
            : '-'
        }</td>
        <td>${table.crcValid === undefined ? '-' : table.crcValid ? '<span class="ok">ok</span>' : '<span class="bad">BAD</span>'}</td>
        <td class="num">${table.occurrences}</td>
        <td class="num">${table.length}</td>
        <td class="num">${table.firstPacket}</td>
      </tr>`,
    )
    .join('');

  return `<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>tsinspect tables - ${escapeHtml(result.source.name)}</title>
<style>
:root {
  color-scheme: light dark;
  --bg: #ffffff;
  --fg: #1b1b1f;
  --muted: #62626b;
  --border: #d9d9e0;
  --accent: #0b5fff;
  --ok: #0a7a33;
  --err: #b00020;
  --card: #f6f6f9;
}
@media (prefers-color-scheme: dark) {
  :root {
    --bg: #151519;
    --fg: #ececf1;
    --muted: #a0a0aa;
    --border: #34343d;
    --accent: #6ea0ff;
    --ok: #58d68d;
    --err: #ff7b86;
    --card: #1e1e25;
  }
}
* { box-sizing: border-box; }
body {
  margin: 0;
  padding: 2rem 1.25rem 4rem;
  background: var(--bg);
  color: var(--fg);
  font: 14px/1.5 system-ui, -apple-system, "Segoe UI", Roboto, sans-serif;
}
main { max-width: 1100px; margin: 0 auto; }
h1 { font-size: 1.5rem; margin: 0 0 .25rem; }
p { margin: .35rem 0; }
.muted { color: var(--muted); }
.mono, code { font-family: ui-monospace, SFMono-Regular, Consolas, monospace; }
.num { text-align: right; font-variant-numeric: tabular-nums; }
table { width: 100%; border-collapse: collapse; margin: 1rem 0; font-size: 13px; }
th, td { padding: .4rem .55rem; border-bottom: 1px solid var(--border); text-align: left; vertical-align: top; }
th { font-weight: 600; background: var(--card); white-space: nowrap; }
.ok { color: var(--ok); }
.bad { color: var(--err); font-weight: 600; }
footer { margin-top: 3rem; color: var(--muted); font-size: 12px; }
</style>
</head>
<body>
<main>
  <h1>${escapeHtml(result.source.name)}</h1>
  <p class="muted">MPEG-TS table index &middot; ${escapeHtml(result.standard.detected)} &middot; tsinspect ${escapeHtml(
    result.tool.version,
  )}</p>
  <p class="muted">${visible.length} table(s), ${formatBytes(result.source.sampledBytes)} sampled${
    result.source.size !== undefined ? ` of ${formatBytes(result.source.size)}` : ''
  }</p>
  <table>
    <thead><tr>
      <th>PID</th><th>Table</th><th>ID</th><th>Ext</th><th>Ver</th><th>Sec</th>
      <th>CRC</th><th>Occ</th><th>Bytes</th><th>Packet</th>
    </tr></thead>
    <tbody>${rows}</tbody>
  </table>
  <footer>Generated by tsinspect ${escapeHtml(result.tool.version)}</footer>
</main>
</body>
</html>`;
}

function escapeHtml(value: string): string {
  return value
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
